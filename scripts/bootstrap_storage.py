"""Create the S3 buckets and upload commands_pool.jsonl (Task 1, step 2).

Creates buckets `datasets` and `models`, then uploads data/commands_pool.jsonl to
datasets/commands_pool.jsonl and verifies it.

Run from the host against a port-forwarded SeaweedFS:
  kubectl port-forward -n data svc/seaweedfs 8333:8333    # in another terminal
  python scripts/bootstrap_storage.py

Credentials are read from .secrets/s3.env (generated by setup_secrets.py); the
host endpoint defaults to http://localhost:8333.
"""
import os
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "worker"))

# Load host credentials/endpoint from .secrets/s3.env before importing the client.
env_file = ROOT / ".secrets" / "s3.env"
if env_file.exists():
    for line in env_file.read_text().splitlines():
        if "=" in line and not line.startswith("#"):
            k, v = line.split("=", 1)
            os.environ.setdefault(k.strip(), v.strip())
os.environ.setdefault("S3_ENDPOINT", os.environ.get("S3_ENDPOINT_HOST", "http://localhost:8333"))

from s3_util import ensure_bucket, s3_client  # noqa: E402

COMMANDS = ROOT / "data" / "commands_pool.jsonl"
BUCKETS = ["datasets", "models"]
KEY = "commands_pool.jsonl"


def main():
    c = s3_client()
    print(f"endpoint: {os.environ['S3_ENDPOINT']}")
    for b in BUCKETS:
        ensure_bucket(c, b)
        print(f"  bucket ready: {b}")

    c.upload_file(str(COMMANDS), "datasets", KEY)
    head = c.head_object(Bucket="datasets", Key=KEY)
    local_size = COMMANDS.stat().st_size
    print(f"uploaded datasets/{KEY}: {head['ContentLength']} bytes (local {local_size})")
    assert head["ContentLength"] == local_size, "size mismatch after upload"

    print("\nbuckets:", [b["Name"] for b in c.list_buckets()["Buckets"]])
    print("datasets contents:",
          [o["Key"] for o in c.list_objects_v2(Bucket="datasets").get("Contents", [])])


if __name__ == "__main__":
    main()
